import { useState } from 'react';
import { Bookmark, BookmarkCheck, RotateCcw, Share2, Calendar, Compass, Sliders } from 'lucide-react';
import CopyButton from './CopyButton';
import ConfirmDialog from './ConfirmDialog';
import { useToast } from '../context/ToastContext';

export default function ScenarioHeader({
  scenario,
  isSaved,
  onToggleSave,
  onRegenerate,
}) {
  const [showRegenConfirm, setShowRegenConfirm] = useState(false);
  const toast = useToast();

  const handleShare = async () => {
    try {
      if (navigator.clipboard) {
        await navigator.clipboard.writeText(window.location.href);
        toast.success('Scenario URL copied to clipboard');
      }
    } catch {
      toast.info('Share via address bar');
    }
  };

  const fullTextToCopy = `WHATIF WORLD ATLAS — ${scenario.title}
${scenario.tagline}

PREMISE:
${scenario.premise}

ASSUMPTIONS:
${scenario.assumptions?.map((a, i) => `${i + 1}. ${a}`).join('\n')}

CHRONOLOGICAL TIMELINE:
${scenario.timeline?.map((t) => `• ${t.yearLabel}: ${t.eventTitle} — ${t.description}`).join('\n')}

DIMENSIONAL IMPACTS:
• Society: ${scenario.impacts?.society}
• Economy: ${scenario.impacts?.economy}
• Technology: ${scenario.impacts?.technology}
• Environment: ${scenario.impacts?.environment}
• Culture: ${scenario.impacts?.culture}

SPECULATIVE STORY: "${scenario.story?.title}"
${scenario.story?.body}

(Generated by WhatIf AI — Fictional thought experiment)`;

  const formattedDate = scenario.createdAt
    ? new Date(scenario.createdAt).toLocaleDateString('en-US', {
        month: 'short',
        day: 'numeric',
        year: 'numeric',
      })
    : 'Recent Archive';

  return (
    <header className="pb-8 border-b border-paper-300">
      {/* Top Meta Bar */}
      <div className="flex flex-wrap items-center justify-between gap-3 text-xs text-ink-faint mb-4">
        <div className="flex items-center gap-2">
          <span className="font-sans font-bold tracking-widest uppercase text-accent">
            Atlas Dossier
          </span>
          <span>•</span>
          <span className="flex items-center gap-1">
            <Calendar className="w-3.5 h-3.5" aria-hidden="true" />
            {formattedDate}
          </span>
          {scenario.tone && (
            <>
              <span>•</span>
              <span className="flex items-center gap-1">
                <Sliders className="w-3.5 h-3.5" aria-hidden="true" />
                {scenario.tone} Tone
              </span>
            </>
          )}
          {scenario.timelineScale && (
            <>
              <span>•</span>
              <span className="flex items-center gap-1">
                <Compass className="w-3.5 h-3.5" aria-hidden="true" />
                {scenario.timelineScale}-Year Scope
              </span>
            </>
          )}
        </div>

        {/* Global Actions */}
        <div className="flex items-center gap-2">
          <CopyButton
            text={fullTextToCopy}
            label="Copy Full Dossier"
            toastMessage="Full scenario copied to clipboard"
          />

          <button
            type="button"
            onClick={onToggleSave}
            className={`inline-flex items-center gap-1.5 text-xs font-medium px-3 py-1.5 rounded border transition-colors ${
              isSaved
                ? 'bg-accent text-white border-accent hover:bg-accent-hover'
                : 'bg-paper-50 border-paper-300 text-ink-muted hover:text-ink hover:bg-paper-200'
            }`}
            aria-pressed={isSaved}
          >
            {isSaved ? (
              <>
                <BookmarkCheck className="w-3.5 h-3.5" aria-hidden="true" />
                <span>Saved</span>
              </>
            ) : (
              <>
                <Bookmark className="w-3.5 h-3.5" aria-hidden="true" />
                <span>Save Scenario</span>
              </>
            )}
          </button>

          <button
            type="button"
            onClick={handleShare}
            className="p-1.5 rounded border border-paper-300 bg-paper-50 hover:bg-paper-200 text-ink-muted hover:text-ink transition-colors"
            title="Copy scenario link"
            aria-label="Copy scenario link"
          >
            <Share2 className="w-3.5 h-3.5" />
          </button>

          {onRegenerate && (
            <button
              type="button"
              onClick={() => setShowRegenConfirm(true)}
              className="p-1.5 rounded border border-paper-300 bg-paper-50 hover:bg-paper-200 text-ink-muted hover:text-ink transition-colors"
              title="Regenerate this scenario"
              aria-label="Regenerate this scenario"
            >
              <RotateCcw className="w-3.5 h-3.5" />
            </button>
          )}
        </div>
      </div>

      {/* Main Title & Subtitle */}
      <h1 className="font-serif text-3xl sm:text-4xl lg:text-5xl font-bold text-ink tracking-tight mb-3">
        {scenario.title}
      </h1>
      <p className="font-serif text-lg sm:text-xl text-accent font-medium italic mb-6">
        {scenario.tagline}
      </p>

      {/* Inquiry Source Badge */}
      {scenario.prompt && (
        <div className="inline-flex items-baseline gap-2 px-3 py-1.5 rounded bg-paper-200/80 border border-paper-300 text-xs text-ink-muted">
          <span className="font-semibold uppercase tracking-wider text-ink-faint text-[0.65rem]">
            Counterfactual Inquiry:
          </span>
          <span className="italic">"{scenario.prompt}"</span>
        </div>
      )}

      {/* Regenerate Confirmation Dialog */}
      <ConfirmDialog
        isOpen={showRegenConfirm}
        title="Regenerate this scenario?"
        message="A new reality will be generated for this inquiry. Your current unsaved scenario will be replaced."
        confirmLabel="Regenerate"
        onConfirm={() => {
          setShowRegenConfirm(false);
          onRegenerate();
        }}
        onCancel={() => setShowRegenConfirm(false)}
      />
    </header>
  );
}
